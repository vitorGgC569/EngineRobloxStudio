	square.

		local Textures = Forge.Catalog.Textures
		local grass = Textures.pick("ground.grass", 7)
		Forge.Material.define("MeadowGrass", {
			base = Enum.Material.Grass, colorMap = grass.id, studsPerTile = 4,
		})
