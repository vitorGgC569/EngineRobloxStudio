-- ================================= lookup ===================================
function Catalog.byCategory(category: string): { any }
	local out = {}
	for _, entry in Catalog.entries do
		if entry.category == category then
			table.insert(out, entry)
		end
	end
	return out
end

function Catalog.byPack(pack: string): { any }
	local out = {}
	for _, entry in Catalog.entries do
		if entry.pack == pack then
			table.insert(out, entry)
		end
	end
	return out
end

function Catalog.find(text: string): { any }
	local needle = text:lower()
	local out = {}
	for _, entry in Catalog.entries do
		if entry.name:lower():find(needle, 1, true) then
			table.insert(out, entry)
		end
	end
	return out
end

function Catalog.categories(): { string }
	local seen, out = {}, {}
	for _, entry in Catalog.entries do
		if not seen[entry.category] then
			seen[entry.category] = true
			table.insert(out, entry.category)
		end
	end
	table.sort(out)
	return out
end

-- Whether a pack id may be inserted at all. `Assets` calls this before
-- anything reaches the world, which is what stops an invented id from
-- reaching a player.
function Catalog.verifiedPack(packId: number): boolean
	for _, pack in Catalog.packs do
		if pack.id == packId then
			return true
		end
	end
	return false
end

--[[
	Insert a piece and hand back a clone of it.

	Packs are loaded once and cached: a pack is a single asset containing
	dozens of pieces, so fetching it again for the second tree is dozens of
	needless round trips.
]]
local packCache: { [number]: Instance } = {}

--: Seconds to wait for one pack before falling back. Per pack, not per piece.
Catalog.loadTimeout = 8

--: Packs that already refused, so a scatter of two hundred pieces pays the
--: timeout once rather than two hundred times.
local failedPacks: { [number]: boolean } = {}

local function loadPack(packId: number): Instance?
	if packCache[packId] then
		return packCache[packId]
	end
	if failedPacks[packId] then
		return nil
	end
	if not Catalog.verifiedPack(packId) then
		warn(string.format("[Catalog] pack %d is not in the verified list", packId))
		return nil
	end
	--[[
		Bounded, because `LoadAsset` does not always come back.

		A `pcall` catches an error and does nothing about a hang, and this
		hangs: in a play session on an unpublished place the request is
		refused somewhere that never answers. The whole world generator waited
		on it — no terrain, no props, no players, and a server that printed
		its last line and then simply stopped. Nothing in the log said the
		word "asset".

		Giving up produces the fallback geometry instead, which is the rule
		this catalogue already lives by: a world with worse rocks is a world,
		and a world with no rocks is a bug. The failure is cached so the next
		two hundred pieces do not each pay the timeout.
	]]
	local finished, ok, container = false, false, nil
	task.spawn(function()
		ok, container = pcall(function()
			return InsertService:LoadAsset(packId)
		end)
		finished = true
	end)

	local deadline = os.clock() + Catalog.loadTimeout
	while not finished and os.clock() < deadline do
		task.wait(0.05)
	end

	if not finished then
		warn(string.format(
			"[Catalog] pack %d did not answer within %.0fs; using fallback geometry",
			packId, Catalog.loadTimeout))
		failedPacks[packId] = true
		return nil
	end
	if not ok or not container then
		warn(string.format("[Catalog] pack %d failed to load: %s", packId, tostring(container)))
		failedPacks[packId] = true
		return nil
	end
	packCache[packId] = container
	return container
end

-- =============================== local kits =================================
--[[
	Content that ships with the place instead of being fetched.

	`InsertService:LoadAsset` needs a published experience and a network round
	trip, and on an unpublished build it does not fail — it hangs, which cost
	this project a whole afternoon of a server that booted and never finished.
	A kit is the other half of the answer: `.rbxm` files mounted by rojo, in
	the place file, available the instant the game starts.

	It is also the only way to use content you hold a licence to but have not
	uploaded. Nothing here reaches the network.

		Catalog.mountKit(ReplicatedStorage.Kits.halo)
		Catalog.fromKit("guardians", "SentinelA")

	Kits are searched before packs, so a piece present locally is never
	fetched. Falling back the other way would mean a slow path shadowing a
	fast one that was already there.
]]
local kits: { Instance } = {}

function Catalog.mountKit(container: Instance?): boolean
	if not container then
		return false
	end
	if table.find(kits, container) then
		return false
	end
	table.insert(kits, container)
	return true
end

function Catalog.kitNames(): { string }
	local names = {}
	for _, kit in kits do
		table.insert(names, kit.Name)
	end
	table.sort(names)
	return names
end

--[[
	Find a piece by name in any mounted kit.

	Deep search, because a kit is however the licensed project happened to
	organise itself and insisting on a flat folder would mean re-organising
	somebody else's export by hand.
]]
--[[
	One piece out of a mounted kit, by name.

	`className` is the whole reason this takes a second argument. Without it
	the answer was hardcoded to "a Model or a BasePart", which was right while
	a kit held nothing but props and quietly wrong the moment the harvester
	started shelving animations, tools and HUDs: eighty-nine `KeyframeSequence`
	files sat in the place, mounted and correct, and no call could ever reach
	one. Extracted and reachable are not the same thing, and only the second is
	worth anything.

	The default stays props, because every existing caller asks for a machine
	and would be badly served by a Sound that happens to share its name.
]]
local function acceptable(thing: Instance, className: string?): boolean
	if className then
		return thing:IsA(className)
	end
	return thing:IsA("Model") or thing:IsA("BasePart")
end

function Catalog.fromKit(name: string, className: string?): Instance?
	for _, kit in kits do
		--[[
			The fast path first, then a real search.

			`FindFirstChild(name, true)` returns *a* descendant with that name,
			not the one that was asked for, and a kit is full of repeated
			names: the animation shelf holds clips called "1", "2", "3", and so
			does the button row of every HUD in the place. Checking the first
			hit and giving up returned nil for animations that were mounted,
			present and three folders further down -- a lookup that reported
			the library was empty while standing in it.
		]]
		local found = kit:FindFirstChild(name, true)
		if found and acceptable(found, className) then
			return found:Clone()
		end

		for _, descendant in kit:GetDescendants() do
			if descendant.Name == name and acceptable(descendant, className) then
				return descendant:Clone()
			end
		end
	end
	return nil
end

--[[
	What is on one shelf of the harvest.

	The harvester writes into `harvest/<category>/`, so the folder name *is* the
	category and asking the kit is cheaper and truer than keeping a manifest in
	Luau that drifts from the files on disk.
]]
function Catalog.kitShelf(category: string): { string }
	local out = {}
	for _, kit in kits do
		local harvest = kit:FindFirstChild("harvest")
		local shelf = harvest and harvest:FindFirstChild(category)
		if shelf then
			for _, piece in shelf:GetChildren() do
				table.insert(out, piece.Name)
			end
		end
	end
	return out
end

--- Every category any mounted kit has anything on.
function Catalog.kitShelves(): { string }
	local seen, out = {}, {}
	for _, kit in kits do
		local harvest = kit:FindFirstChild("harvest")
		if harvest then
			for _, shelf in harvest:GetChildren() do
				if not seen[shelf.Name] then
					seen[shelf.Name] = true
					table.insert(out, shelf.Name)
				end
			end
		end
	end
	table.sort(out)
	return out
end

--: Everything a kit holds, as ids you can pass to `fromKit`.
function Catalog.kitPieces(limit: number?): { string }
	local out = {}
	local cap = limit or 200
	for _, kit in kits do
		for _, descendant in kit:GetDescendants() do
			if descendant:IsA("Model") or descendant:IsA("MeshPart") then
				table.insert(out, descendant.Name)
				if #out >= cap then
					return out
				end
			end
		end
	end
	return out
end

function Catalog.load(entry: any): Instance?
	-- A local kit first: it is already in the place, so it cannot hang and
	-- cannot be moderated away between one session and the next.
	if entry.name then
		local local_ = Catalog.fromKit(entry.name)
		if local_ then
			return local_
		end
	end

	local container = loadPack(entry.packId)
	if not container then
		return nil
	end
	local found = container:FindFirstChild(entry.name, true)
	if not found then
		warn(string.format("[Catalog] '%s' is not inside pack %d any more", entry.name, entry.packId))
		return nil
	end
	return found:Clone()
end

function Catalog.describe(): { [string]: any }
	local byCategory: { [string]: number } = {}
	for _, entry in Catalog.entries do
		byCategory[entry.category] = (byCategory[entry.category] or 0) + 1
	end
	return {
		generated = Catalog.generated,
		entries = #Catalog.entries,
		packs = #Catalog.packs,
		categories = byCategory,
	}
end

return Catalog
