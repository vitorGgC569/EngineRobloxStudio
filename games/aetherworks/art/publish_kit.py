"""Publish the reviewed original kit; reuse hash-matching upload receipts."""
from pathlib import Path
import hashlib,json,sys,time
ROOT=Path(__file__).resolve().parents[3];sys.path.insert(0,str(ROOT))
from rqe.hub.client import StudioBridge
from rqe.geometry.publication import publish_mesh
from rqe.hub.protocol import BridgeError
BASE=Path(__file__).resolve().parent
manifest=json.loads((BASE/'kit.json').read_text())
receipt=BASE/'published.json'
published=json.loads(receipt.read_text()) if receipt.exists() else {}
b=StudioBridge();b.pin_to_context('edit')
for name,asset in manifest.items():
    path=BASE.parent/asset['meshData'];sha=hashlib.sha256(path.read_bytes()).hexdigest()
    previous=published.get(name,{})
    if previous.get('sha256')==sha and previous.get('status')=='PUBLISHED':continue
    if previous.get('status')=='UNCERTAIN':raise RuntimeError('Review uncertain upload before retrying: '+name)
    published[name]={'status':'UNCERTAIN','sha256':sha};receipt.write_text(json.dumps(published,indent=2))
    try:
        with b.lease_scope(agent_id='art-publication',context='edit',ttl_seconds=120):
            result=publish_mesh(b,json.loads(path.read_text()),'Aetherworks '+name+' v2')
    except BridgeError as error:
        if any(code in str(error) for code in ['E_BAD_PARAMS','E_UNAUTHORIZED','E_LEASE_REQUIRED']):
            published[name]={'status':'NOT_SENT','sha256':sha,'reason':str(error)}
            receipt.write_text(json.dumps(published,indent=2))
        raise
    result=result.get('result',result)
    published[name]={**result,'sha256':sha};receipt.write_text(json.dumps(published,indent=2))
    print(name,result,flush=True)
    if result.get('status')!='PUBLISHED':raise RuntimeError(result)
    time.sleep(2.1)
lines=['-- Published original models. Generated by art/publish_kit.py.','return {']
for name,entry in published.items():
    if entry.get('status')=='PUBLISHED':lines.append('    '+name+'="rbxassetid://'+str(entry['assetId'])+'",')
lines.append('}')
(BASE.parent/'src/shared/PublishedArt.lua').write_text('\n'.join(lines),encoding='utf-8')
