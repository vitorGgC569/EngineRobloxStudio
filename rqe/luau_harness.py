"""Execute SDK Luau modules headlessly, outside Roblox.

The engine plan rests on one architectural claim: SDK modules are pure Luau and
therefore run in three places -- a Studio plugin, a published experience, and an
Open Cloud Luau task. That claim is worth nothing while the only way to run the
code is to open Studio.

This module makes it checkable. It resolves Roblox's `require(script.Parent.X)`
module graph, prepends a minimal engine shim, and runs the result under the
pinned Luau CLI. A module that reaches for an engine feature the shim does not
provide fails loudly, which is the right answer: it means that module is not
portable and the claim does not hold for it.

The same path is what makes headless economy simulation possible -- thousands of
simulated player-hours against the shipped catalogue, with no game running.
"""

from __future__ import annotations

import json
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable, Sequence

from .luau_check import ToolchainUnavailable, toolchain_dir


_MODULE_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class HarnessError(RuntimeError):
    """The harness could not build or run the script."""


@dataclass(frozen=True)
class HarnessResult:
    exit_code: int
    stdout: str
    stderr: str
    script: str

    @property
    def ok(self) -> bool:
        return self.exit_code == 0

    def lines(self) -> list[str]:
        return [line for line in self.stdout.splitlines() if line.strip()]

    def json_lines(self) -> list[Any]:
        """Decode every stdout line that is JSON, ignoring plain prints."""

        decoded: list[Any] = []
        for line in self.lines():
            try:
                decoded.append(json.loads(line))
            except json.JSONDecodeError:
                continue
        return decoded


def runtime_path(root: Path) -> Path:
    import os

    name = "luau.exe" if os.name == "nt" else "luau"
    return toolchain_dir(root) / name


def ensure_runtime(root: Path) -> Path:
    path = runtime_path(root)
    if not path.is_file():
        raise ToolchainUnavailable(
            f"Luau runtime missing at {path}; run `python -m rqe.luau_check --bootstrap`"
        )
    return path


def _lua_string(value: str) -> str:
    """Long-bracket literal with a level that cannot appear in the payload."""

    level = 0
    while f"]{'=' * level}]" in value or f"[{'=' * level}[" in value:
        level += 1
    equals = "=" * level
    # A leading newline is stripped by Lua inside long brackets, so one is added
    # to protect sources that legitimately begin with one.
    return f"[{equals}[\n{value}]{equals}]"


def to_lua_literal(value: Any, indent: int = 0) -> str:
    """Render JSON-shaped Python data as a Lua table literal.

    Used to hand token sets and catalogues to the harness without inventing a
    second serialisation format: the data the game reads is the data the
    simulation reads.
    """

    pad = "\t" * indent
    inner = "\t" * (indent + 1)
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, str):
        return _lua_string(value) if "\n" in value else json.dumps(value)
    if isinstance(value, (list, tuple)):
        if not value:
            return "{}"
        items = ",\n".join(f"{inner}{to_lua_literal(item, indent + 1)}" for item in value)
        return "{\n" + items + f",\n{pad}" + "}"
    if isinstance(value, dict):
        if not value:
            return "{}"
        rows = []
        for key in value:
            rendered = to_lua_literal(value[key], indent + 1)
            if isinstance(key, str) and _MODULE_NAME.match(key):
                rows.append(f"{inner}{key} = {rendered}")
            else:
                rows.append(f"{inner}[{json.dumps(str(key))}] = {rendered}")
        return "{\n" + ",\n".join(rows) + f",\n{pad}" + "}"
    raise HarnessError(f"cannot render {type(value).__name__} as a Lua literal")


def collect_library(directory: Path) -> dict[str, str]:
    """Read every module in a library directory, keyed by require-able name."""

    directory = Path(directory)
    if not directory.is_dir():
        raise HarnessError(f"library directory does not exist: {directory}")
    modules: dict[str, str] = {}
    for path in sorted(directory.glob("*.lua")):
        name = path.stem
        if name == "init":
            name = directory.name
        if not _MODULE_NAME.match(name):
            raise HarnessError(f"module name is not require-able: {path}")
        modules[name] = path.read_text(encoding="utf-8")
    return modules


_PRELUDE = """\
-- Generated by rqe.luau_harness. Do not edit; edit the shim or the SDK.
local __shim = (function()
{shim}
end)()

Color3 = __shim.Color3
Vector2 = __shim.Vector2
Vector3 = __shim.Vector3
UDim = __shim.UDim
UDim2 = __shim.UDim2
CFrame = __shim.CFrame
Random = __shim.Random
Font = __shim.Font
NumberRange = __shim.NumberRange
ColorSequence = __shim.ColorSequence
NumberSequence = __shim.NumberSequence
ColorSequenceKeypoint = __shim.ColorSequenceKeypoint
NumberSequenceKeypoint = __shim.NumberSequenceKeypoint
Instance = __shim.Instance
Enum = __shim.Enum
typeof = __shim.typeof
game = __shim.game
task = __shim.task
warn = __shim.warn
Harness = __shim

local __sources = {{}}
local __cache = {{}}
local __loading = {{}}

-- A token standing in for a Roblox ModuleScript reference. `script.Parent.X`
-- produces one of these; `require` turns it back into a loaded module.
--
-- Tokens are themselves indexable so that a nested path such as
-- `script.Parent.Parent.WorldKit.Blockout` resolves to its final segment. The
-- harness namespace is flat -- one entry per module basename -- so the leaf is
-- the only part that identifies the module, and walking the intermediate
-- folders is exactly what Roblox is doing too.
local function __token(name)
	return setmetatable({{ __module = name }}, {{
		__index = function(_, key)
			return __token(key)
		end,
		__tostring = function()
			return "ModuleRef(" .. name .. ")"
		end,
	}})
end

local function __proxy(selfName)
	local proxy = {{}}
	return setmetatable(proxy, {{
		__index = function(_, key)
			if key == "Parent" then
				return __proxy(selfName)
			end
			if key == "Name" then
				return selfName
			end
			return __token(key)
		end,
	}})
end

local function __require(target)
	if type(target) ~= "table" or target.__module == nil then
		error("[harness] require expects a module reference, got " .. tostring(target), 2)
	end
	local name = target.__module
	if __cache[name] ~= nil then
		return __cache[name]
	end
	if __loading[name] then
		error("[harness] circular require of " .. name, 2)
	end
	local factory = __sources[name]
	if factory == nil then
		error("[harness] module not loaded into the harness: " .. name, 2)
	end
	__loading[name] = true
	local result = factory(__proxy(name), __require)
	__loading[name] = false
	if result == nil then
		error("[harness] module " .. name .. " returned nil", 2)
	end
	__cache[name] = result
	return result
end

Require = function(name)
	return __require(__token(name))
end

-- The shim's storage containers hand out tokens, and they are built before
-- this line runs, so the constructor is handed over rather than left in a
-- global -- `_G` is read-only here.
__shim.useTokens(__token)
"""


def build_script(
    *,
    shim_source: str,
    modules: dict[str, str],
    body: str,
    data: dict[str, Any] | None = None,
) -> str:
    """Assemble one self-contained Luau script."""

    parts = [_PRELUDE.format(shim=shim_source)]

    for name in sorted(modules):
        source = modules[name]
        parts.append(
            f"__sources[{json.dumps(name)}] = function(script, require)\n"
            f"{source}\n"
            f"end\n"
        )

    for key, value in (data or {}).items():
        if not _MODULE_NAME.match(key):
            raise HarnessError(f"data key is not a valid Lua identifier: {key}")
        parts.append(f"{key} = {to_lua_literal(value)}\n")

    parts.append("\n-- test body\n")
    parts.append(body)
    return "\n".join(parts)


def run(
    root: Path,
    *,
    libraries: Sequence[Path | str],
    body: str,
    data: dict[str, Any] | None = None,
    timeout: float = 60.0,
    keep_script: Path | None = None,
) -> HarnessResult:
    """Run `body` with the given SDK libraries loaded."""

    root = Path(root)
    runtime = ensure_runtime(root)
    shim_path = root / "tools" / "luau-harness" / "shim.luau"
    if not shim_path.is_file():
        raise HarnessError(f"harness shim missing at {shim_path}")

    modules: dict[str, str] = {}
    for library in libraries:
        directory = Path(library)
        if not directory.is_absolute():
            directory = root / directory
        for name, source in collect_library(directory).items():
            if name in modules:
                raise HarnessError(f"module name collides across libraries: {name}")
            modules[name] = source

    script = build_script(
        shim_source=shim_path.read_text(encoding="utf-8"),
        modules=modules,
        body=body,
        data=data,
    )

    import tempfile

    with tempfile.TemporaryDirectory() as directory:
        script_path = Path(directory) / "harness.luau"
        script_path.write_text(script, encoding="utf-8")
        if keep_script is not None:
            Path(keep_script).write_text(script, encoding="utf-8")
        process = subprocess.run(
            [str(runtime), str(script_path)],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
            timeout=timeout,
        )

    return HarnessResult(
        exit_code=process.returncode,
        stdout=process.stdout,
        stderr=process.stderr,
        script=script,
    )


def run_or_raise(root: Path, **kwargs: Any) -> HarnessResult:
    result = run(root, **kwargs)
    if not result.ok:
        raise HarnessError(
            "harness script failed\n"
            f"exit={result.exit_code}\n"
            f"stdout:\n{result.stdout}\n"
            f"stderr:\n{result.stderr}"
        )
    return result
