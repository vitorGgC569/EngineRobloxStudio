"""Content generation.

Generating a hundred items is not the hard part. The hard part is that a
catalogue generated by hand or by prompt is quietly incoherent -- a tier-5 enemy
weaker than a tier-4, a rarity nobody can roll, a variant strictly worse than
its neighbour, a drop table summing to 0.97. None of those crash. All of them
are felt.

So the tests are mostly about the two validators, and especially `balance`: a
well-formed unfair catalogue passes every other check in the engine.

`test_names_are_unique_by_construction` exists because the first version was
not. Six tier prefixes across eight tiers made every role collide at tiers 6, 7
and 8, and the consistency check caught it on its first run.
"""

from __future__ import annotations

import unittest

from rqe.content import (
    RARITIES,
    Catalogue,
    ContentError,
    ContentSchema,
    Entry,
    balance,
    build,
    consistency,
    drop_table,
    from_model,
    generate,
)
from rqe.ir import load_model


ROBOTS = ContentSchema(
    id="corrupted-robots", kind="enemy", theme="corrupted robot",
    tiers=8, variants_per_tier=4,
    roles=("melee", "ranged", "tank", "support"), seed=7,
)


class TestSchema(unittest.TestCase):
    def test_a_themeless_family_is_refused(self):
        """Names are composed from the theme; without one the catalogue reads
        like a different game's."""

        with self.assertRaises(ContentError):
            ContentSchema(id="x", kind="enemy", theme="  ", tiers=3)

    def test_more_roles_than_variants_is_refused(self):
        """Some role would be missing from every tier, which is a strategy that
        stops working for no stated reason."""

        with self.assertRaises(ContentError) as caught:
            ContentSchema(id="x", kind="enemy", theme="t", tiers=3,
                          variants_per_tier=2, roles=("melee", "ranged", "tank"))
        self.assertIn("missing from every tier", str(caught.exception))

    def test_a_power_step_outside_the_band_is_refused(self):
        with self.assertRaises(ContentError):
            ContentSchema(id="x", kind="enemy", theme="t", tiers=3, power_step=9.0)
        with self.assertRaises(ContentError):
            ContentSchema(id="x", kind="enemy", theme="t", tiers=3, power_step=1.0)

    def test_an_unknown_kind_lists_the_real_ones(self):
        with self.assertRaises(ContentError) as caught:
            ContentSchema(id="x", kind="vehicle", theme="t", tiers=3)
        self.assertIn("enemy", str(caught.exception))


class TestGeneration(unittest.TestCase):
    def test_the_documents_example_generates_cleanly(self):
        """corrupted_robot, 8 tiers, 4 variants, 4 roles -- the family the
        MetaWorldModel document names."""

        report = build(ROBOTS)
        self.assertTrue(report["ok"], report["consistency"] + report["balance"])
        self.assertEqual(report["catalogue"]["count"], 32)

    def test_generation_is_deterministic(self):
        """A difference has to be a change somebody made, not a re-roll."""

        self.assertEqual(generate(ROBOTS).to_dict(), generate(ROBOTS).to_dict())

    def test_a_different_seed_gives_a_different_catalogue(self):
        other = ContentSchema(**{**ROBOTS.__dict__, "seed": 99})
        self.assertNotEqual(generate(ROBOTS).to_dict(), generate(other).to_dict())

    def test_names_are_unique_by_construction(self):
        """Two entries a player cannot tell apart are one entry as far as they
        are concerned. The first version collided at every tier past the sixth."""

        for tiers in (4, 8, 12, 20):
            schema = ContentSchema(
                id="probe", kind="enemy", theme="corrupted robot", tiers=tiers,
                variants_per_tier=4, roles=("melee", "ranged", "tank", "support"))
            names = [entry.name for entry in generate(schema).entries]
            self.assertEqual(len(set(names)), len(names), f"{tiers} tiers")

    def test_every_tier_covers_every_role(self):
        grouped = generate(ROBOTS).by_tier()
        for tier, entries in grouped.items():
            self.assertEqual({e.role for e in entries}, set(ROBOTS.roles), tier)

    def test_names_carry_the_theme(self):
        for entry in generate(ROBOTS).entries:
            self.assertIn("Corrupted Robot", entry.name)

    def test_every_role_spends_its_whole_power_budget(self):
        """A role that spent less would be a strictly dominated choice, which is
        the balance failure the shape table exists to avoid."""

        for entry in generate(ROBOTS).entries:
            self.assertAlmostEqual(sum(entry.stats.values()), entry.power, delta=0.01)


class TestConsistency(unittest.TestCase):
    def test_a_clean_catalogue_reports_nothing(self):
        self.assertEqual(consistency(generate(ROBOTS)), [])

    def test_a_duplicate_id_is_caught(self):
        """A runtime catalogue keyed by id would silently lose one of each
        pair."""

        catalogue = generate(ROBOTS)
        catalogue.entries.append(catalogue.entries[0])
        rules = [item["rule"] for item in consistency(catalogue)]
        self.assertIn("duplicate-id", rules)

    def test_an_empty_tier_is_caught(self):
        catalogue = generate(ROBOTS)
        catalogue.entries = [e for e in catalogue.entries if e.tier != 4]
        rules = [item["rule"] for item in consistency(catalogue)]
        self.assertIn("empty-tier", rules)

    def test_a_missing_role_in_one_tier_is_caught(self):
        catalogue = generate(ROBOTS)
        catalogue.entries = [
            e for e in catalogue.entries if not (e.tier == 3 and e.role == "tank")
        ]
        rules = [item["rule"] for item in consistency(catalogue)]
        self.assertIn("role-gap", rules)


class TestBalance(unittest.TestCase):
    """The question a well-formed catalogue can still fail."""

    def test_a_clean_catalogue_reports_nothing(self):
        self.assertEqual(balance(generate(ROBOTS)), [])

    def test_a_tier_that_is_not_stronger_is_caught(self):
        """The player climbs and gets nothing."""

        catalogue = generate(ROBOTS)
        catalogue.entries = [
            Entry(e.id, e.name, e.kind, e.tier, e.role,
                  power=10.0 if e.tier >= 4 else e.power,
                  rarity=e.rarity, stats=e.stats)
            for e in catalogue.entries
        ]
        rules = [item["rule"] for item in balance(catalogue)]
        self.assertIn("tier-not-stronger", rules)

    def test_a_tier_that_invalidates_the_last_is_caught(self):
        catalogue = generate(ROBOTS)
        catalogue.entries = [
            Entry(e.id, e.name, e.kind, e.tier, e.role,
                  power=e.power * (50.0 if e.tier == 5 else 1.0),
                  rarity=e.rarity, stats=e.stats)
            for e in catalogue.entries
        ]
        rules = [item["rule"] for item in balance(catalogue)]
        self.assertIn("tier-invalidates-previous", rules)

    def test_a_dominated_variant_is_caught(self):
        """Worse at everything it shares and offering nothing the other lacks:
        nobody would ever pick it."""

        weak = Entry("weak", "Weak", "enemy", 1, "melee", 5.0, "common",
                     {"attack": 1.0, "health": 1.0, "speed": 1.0})
        strong = Entry("strong", "Strong", "enemy", 1, "tank", 50.0, "common",
                       {"attack": 10.0, "health": 10.0, "speed": 10.0})
        rules = [item["rule"] for item in
                 balance(Catalogue(schema=ROBOTS, entries=[weak, strong]))]
        self.assertIn("dominated-variant", rules)

    def test_a_flat_rarity_spread_is_caught(self):
        """Rarity declared and meaning nothing."""

        catalogue = generate(ROBOTS)
        catalogue.entries = [
            Entry(e.id, e.name, e.kind, e.tier, e.role, e.power, "common", e.stats)
            for e in catalogue.entries
        ]
        rules = [item["rule"] for item in balance(catalogue)]
        self.assertIn("rarity-flat", rules)


class TestDropTable(unittest.TestCase):
    def test_a_table_sums_to_exactly_one(self):
        """A table summing to 0.97 hands the remainder to whichever branch
        happens to be last."""

        for tier in range(1, ROBOTS.tiers + 1):
            table = drop_table(generate(ROBOTS), tier=tier)
            self.assertAlmostEqual(table["sum"], 1.0, places=9, msg=f"tier {tier}")

    def test_every_entry_in_the_tier_is_droppable(self):
        catalogue = generate(ROBOTS)
        table = drop_table(catalogue, tier=3)
        expected = {e.id for e in catalogue.by_tier()[3]}
        self.assertEqual(set(table["entries"]), expected)

    def test_rarer_entries_drop_less(self):
        catalogue = generate(ROBOTS)
        for tier in range(1, ROBOTS.tiers + 1):
            entries = {e.id: e for e in catalogue.by_tier()[tier]}
            table = drop_table(catalogue, tier=tier)["entries"]
            for first, second in zip(list(table), list(table)[1:]):
                if RARITIES.index(entries[first].rarity) < RARITIES.index(entries[second].rarity):
                    self.assertGreaterEqual(table[first], table[second])

    def test_an_empty_tier_is_refused(self):
        with self.assertRaises(ContentError):
            drop_table(generate(ROBOTS), tier=99)


class TestFromModel(unittest.TestCase):
    def test_tiers_come_from_the_game_not_the_caller(self):
        """Content generated for a different number of tiers than the game has
        is content unreachable behind a tier that does not exist."""

        model = load_model({
            "id": "probe", "genre": "tycoon", "theme": "anime farm", "pitch": "x",
            "coreLoop": ["collect", "process", "upgrade", "sell", "unlock"],
            "world": {"topology": "grid_plots", "zones": []},
            "progression": {"kind": "tiered", "tiers": 6, "firstTierSeconds": 45},
            "economy": {"currencies": [
                {"id": "cash", "earnedBy": ["sell"], "spentOn": ["upgrade"]}]},
            "systems": ["economy", "progression", "save", "inventory", "shop", "analytics"],
        })
        schema = from_model(model)
        self.assertEqual(schema.tiers, 6)
        self.assertEqual(schema.theme, "anime farm")

    def test_a_game_with_no_tiers_is_refused(self):
        model = load_model({
            "id": "probe", "genre": "racing", "theme": "t", "pitch": "x",
            "coreLoop": ["race"], "world": {"topology": "linear_levels", "zones": []},
            "progression": {"kind": "endless", "tiers": 0},
            "systems": [],
        })
        with self.assertRaises(ContentError):
            from_model(model)


